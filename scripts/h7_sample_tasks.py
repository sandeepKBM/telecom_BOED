"""[telecom_boed] H7 train-safe rollout sample: seeded, stratified by intent prefix; emits the two H7 run configs.

Pool: telecom_boed.testing.leakage_scan.branch_pool_task_ids(catalog, test40_ids) (no test-40 id, no test-40 fault set).
Sample (seed 1016): 150 mms_issue, 100 mobile_data_issue, min(30, available) service_issue; 280 ids in total.
The sample is shuffled with the same seed, so the first 200 (native run) and the remaining 80 (noncompliant run)
both mix the intents. Configs are written only with --emit-configs and are never overwritten.

Usage (ddl-telecom env, from anywhere):
  /common/users/ss5772/conda_envs/ddl-telecom/bin/python -I scripts/h7_sample_tasks.py            # print composition
  /common/users/ss5772/conda_envs/ddl-telecom/bin/python -I scripts/h7_sample_tasks.py --emit-configs
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]  # .../telecom_boed
sys.path.insert(0, str(HERE / "src"))

from telecom_boed import paths  # noqa: E402
from telecom_boed.testing.leakage_scan import branch_pool_task_ids, parse_task_id  # noqa: E402
from telecom_boed.tau2_ext import register  # noqa: E402

SEED = 1016
QUOTAS = (("mms_issue", 150), ("mobile_data_issue", 100), ("service_issue", 30))  # service_issue: up to 30
NATIVE_N = 200
BASE_CFG = HERE / "configs" / "runs" / "smoke_boedplain_repair_native_train5.yaml"
RUNS = HERE / "configs" / "runs"


def build_sample() -> list[str]:
    tasks_path, split_path = paths.telecom_catalog_paths()
    catalog = json.loads(tasks_path.read_text())
    test40 = json.loads(split_path.read_text())["test"]
    pool = sorted(branch_pool_task_ids(catalog, test40))
    by_intent: dict[str, list[str]] = {}
    for t in pool:
        by_intent.setdefault(parse_task_id(t)[0], []).append(t)
    rng = random.Random(SEED)
    chosen: list[str] = []
    for intent, want in QUOTAS:
        avail = by_intent.get(intent, [])
        n = min(want, len(avail))
        chosen += rng.sample(avail, n)
    rng.shuffle(chosen)
    assert len(set(chosen)) == len(chosen), "duplicate ids in sample"
    assert register.train_safe(chosen), "sample is not train-safe"
    return chosen


def _yaml_block(name: str, user: str, ids: list[str]) -> str:
    """Base smoke config, with the H7 overrides applied. Keys not listed here are copied from BASE_CFG verbatim."""
    overrides = {
        "name": name,
        "status": "ready",
        "user": user,
        "split": "full",
        "task_ids": json.dumps(ids),  # JSON flow list is valid YAML; ids contain [ ] | : so they stay quoted
        "num_trials": "1",
        "seed": "300",
        "max_concurrency": "8",
        "max_steps": "200",
        "eval_final": "false",
    }
    drop = {"num_tasks"}
    out = [
        f"# [telecom_boed] H7 rollout run config (immutable once used: add a new named config, never edit).",
        f"# Generated by scripts/h7_sample_tasks.py --emit-configs (sample seed {SEED}); all ids pass register.train_safe.",
        f"# Other fields are copied from {BASE_CFG.name}.",
    ]
    seen: set[str] = set()
    lines = BASE_CFG.read_text().splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith(" "):  # indented continuation belongs to the previous top-level key (llm:)
            out.append(line)
            continue
        key = line.split(":", 1)[0].strip()
        if key in drop:
            continue
        seen.add(key)
        out.append(f"{key}: {overrides[key]}" if key in overrides else line)
    missing = [k for k in overrides if k not in seen]
    out += [f"{k}: {overrides[k]}" for k in missing]  # keys absent from base (task_ids, eval_final, ...)
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--emit-configs", action="store_true", help="write the two NEW H7 configs (refuses to overwrite)")
    args = ap.parse_args()

    ids = build_sample()
    comp = Counter(parse_task_id(t)[0] for t in ids)
    print(f"sample n={len(ids)} seed={SEED} intents={dict(sorted(comp.items()))}")
    native, ncp = ids[:NATIVE_N], ids[NATIVE_N:]
    print(f"native n={len(native)} intents={dict(Counter(parse_task_id(t)[0] for t in native))}")
    print(f"noncompliant n={len(ncp)} intents={dict(Counter(parse_task_id(t)[0] for t in ncp))}")

    if not args.emit_configs:
        return
    outs = {
        RUNS / "h7_bp_native.yaml": _yaml_block("h7_bp_native", "user_simulator", native),
        RUNS / "h7_bp_noncompliant.yaml": _yaml_block("h7_bp_noncompliant", "boed-user-noncompliant", ncp),
    }
    for path, text in outs.items():
        if path.exists():
            raise SystemExit(f"refusing to overwrite existing config {path}")
        path.write_text(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
