"""[telecom_boed] W4-H18: run eval.parser_accuracy on logged TRAIN-split runs and write results/parsers/accuracy_<date>.md.
Machine-generated; excludes any run whose dir name starts with p3_ (test-40). Usage: python parser_accuracy_report.py <date>"""
import glob, json, os, sys
from telecom_boed.eval.parser_accuracy import evaluate_parsers, load_simulations

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
date = sys.argv[1]
runs = [p for p in sorted(glob.glob(f"{ROOT}/results/runs/*/results.json")) if not os.path.basename(os.path.dirname(p)).startswith("p3_")]
sims, used = [], []
for p in runs:
    s = load_simulations(p); sims += s; used.append((os.path.basename(os.path.dirname(p)), len(s)))
out = {}
for src in ("gold", "parsed"):
    out[src] = evaluate_parsers(sims, requested_source=src)
lines = [f"# Parser accuracy (W4-H18), {date}", "",
         "Generated by `scripts/parser_accuracy_report.py` from `eval/parser_accuracy.py`; do not hand-edit.",
         f"Inputs: {len(used)} train-split runs, {len(sims)} simulations (p3_* test-40 runs excluded). Claim labels: none supplied (claim section skipped).", "",
         "| run | sims |", "|---|---|"] + [f"| {r} | {n} |" for r, n in used] + [""]
for src in ("gold", "parsed"):
    lines += [f"## requested_source={src}", "```json", json.dumps(out[src], indent=1, default=str, sort_keys=True), "```", ""]
os.makedirs(f"{ROOT}/results/parsers", exist_ok=True)
open(f"{ROOT}/results/parsers/accuracy_{date}.md", "w").write("\n".join(lines))
print(f"wrote accuracy_{date}.md sims={len(sims)}")
